-- Modelo relacional para migrar o ambiente Conviva SP de Cloudflare D1
-- para Supabase Postgres. Execute somente no projeto Supabase de destino.

create table if not exists public.escolas (
  id integer primary key,
  nome text not null unique
);

create table if not exists public.ocorrencias (
  id bigint generated by default as identity primary key,
  pedido uuid not null unique,
  escola_id integer not null references public.escolas(id),
  data_ocorrencia date not null,
  tipo varchar(100),
  descricao text,
  gravidade varchar(8) not null check (gravidade in ('AMARELO', 'VERMELHO')),
  registrado_por varchar(12) not null check (registrado_por in ('DIRETOR', 'VICE_DIRETOR', 'OUTROS')),
  registrado_por_outro varchar(100),
  status varchar(30) not null default 'ABERTA',
  criado_em timestamptz not null default now(),
  constraint ck_ocorrencias_responsavel check (
    (registrado_por = 'OUTROS' and registrado_por_outro is not null)
    or (registrado_por <> 'OUTROS' and registrado_por_outro is null)
  )
);

create index if not exists idx_ocorrencias_gravidade on public.ocorrencias (gravidade);
create index if not exists idx_ocorrencias_escola_data on public.ocorrencias (escola_id, data_ocorrencia desc, id desc);

create table if not exists public.ocorrencia_anexos (
  ocorrencia_id bigint primary key references public.ocorrencias(id) on delete cascade,
  tipo varchar(4) not null check (tipo in ('PDF', 'LINK')),
  nome varchar(180),
  url text,
  storage_path text,
  tamanho integer,
  constraint ck_ocorrencia_anexo check (
    (tipo = 'PDF' and nome is not null and storage_path is not null and tamanho between 1 and 5242880 and url is null)
    or (tipo = 'LINK' and url is not null and nome is null and storage_path is null and tamanho is null)
  )
);

create table if not exists public.whatsapp_destinatarios (
  id varchar(20) primary key,
  numero varchar(15) not null default '',
  acesso_versao integer not null default 0 check (acesso_versao >= 0)
);

insert into public.whatsapp_destinatarios (id) values
