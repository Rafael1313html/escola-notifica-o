create table if not exists public.whatsapp_envios (
  id bigint generated by default as identity primary key,
  ocorrencia_id bigint not null references public.ocorrencias(id) on delete cascade,
  destinatario_id varchar(20) not null references public.whatsapp_destinatarios(id),
  numero varchar(15) not null,
  acesso_versao integer not null default 0,
  status varchar(15) not null default 'PENDENTE'
    check (status in ('PENDENTE', 'PROCESSANDO', 'ACEITO', 'FALHOU', 'INCERTO')),
  mensagem_id varchar(255),
  atualizado_em timestamptz not null default now(),
  unique (ocorrencia_id, destinatario_id)
);

create index if not exists idx_whatsapp_pendentes on public.whatsapp_envios (status, id);

-- Nenhuma tabela do sistema fica disponível ao papel anônimo do frontend.
alter table public.escolas enable row level security;
alter table public.ocorrencias enable row level security;
alter table public.ocorrencia_anexos enable row level security;
alter table public.whatsapp_destinatarios enable row level security;
alter table public.whatsapp_envios enable row level security;

